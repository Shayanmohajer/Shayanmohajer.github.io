function classifyPublication(publication) {
  const combined = `${publication.venue} ${publication.title}`.toLowerCase();
  if (combined.includes("patent")) {
    return "patent";
  }
  if (combined.includes("arxiv")) {
    return "preprint";
  }
  if (combined.includes("university of waterloo")) {
    return "thesis";
  }
  return "peer-reviewed";
}

function sortPublications(items) {
  return [...items].sort((a, b) => {
    const yearA = Number.parseInt(a.year || "0", 10) || 0;
    const yearB = Number.parseInt(b.year || "0", 10) || 0;
    if (yearB !== yearA) {
      return yearB - yearA;
    }
    const citesA = Number.parseInt(a.citations || "0", 10) || 0;
    const citesB = Number.parseInt(b.citations || "0", 10) || 0;
    return citesB - citesA;
  });
}

function publicationMarkup(publication) {
  const type = classifyPublication(publication);
  const badges = [
    publication.year ? `<span class="badge">${publication.year}</span>` : "",
    publication.citations ? `<span class="badge">${publication.citations} citations</span>` : "",
    `<span class="badge">${type}</span>`
  ]
    .filter(Boolean)
    .join("");

  return `
    <li class="publication-item">
      <a class="publication-title" href="${publication.url}">${publication.title}</a>
      <p class="publication-authors">${publication.authors}</p>
      <p class="publication-meta">${publication.venue || "Metadata pending on Google Scholar"}</p>
      <div class="publication-badges">${badges}</div>
    </li>
  `;
}

function filterPublications(query, activeFilter) {
  const normalizedQuery = query.trim().toLowerCase();
  return sortPublications(publications).filter((publication) => {
    const typeMatches = activeFilter === "all" || classifyPublication(publication) === activeFilter;
    const haystack = `${publication.title} ${publication.authors} ${publication.venue}`.toLowerCase();
    const queryMatches = !normalizedQuery || haystack.includes(normalizedQuery);
    return typeMatches && queryMatches;
  });
}

function renderPublications(query = "", activeFilter = "all") {
  const publicationList = document.getElementById("publication-list");
  const publicationSummary = document.getElementById("publication-summary");
  const filtered = filterPublications(query, activeFilter);

  publicationList.innerHTML = filtered.map(publicationMarkup).join("");
  publicationSummary.textContent = `Showing ${filtered.length} of ${publications.length} publications.`;
}

function initializePublicationUI() {
  const searchInput = document.getElementById("publication-search");
  const filterButtons = [...document.querySelectorAll(".filter-chip")];
  let activeFilter = "all";

  renderPublications("", activeFilter);

  searchInput.addEventListener("input", () => {
    renderPublications(searchInput.value, activeFilter);
  });

  filterButtons.forEach((button) => {
    button.addEventListener("click", () => {
      activeFilter = button.dataset.filter;
      filterButtons.forEach((candidate) => {
        candidate.classList.toggle("is-active", candidate === button);
      });
      renderPublications(searchInput.value, activeFilter);
    });
  });
}

